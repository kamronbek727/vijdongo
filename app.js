// Fallback: draw a simple curved line if routing API fails
function drawFallbackLine(map, lat1, lng1, lat2, lng2) {
    const midLat = (lat1 + lat2) / 2;
    const midLng = (lng1 + lng2) / 2;
    // Add slight curve offset
    const offset = Math.abs(lat1 - lat2) * 0.15;
    const curvePoints = [
        [lat1, lng1],
        [midLat + offset, midLng],
        [lat2, lng2]
    ];
    const line = new ymaps.Polyline(curvePoints, {}, {
        strokeColor: '#111111',
        strokeWidth: 4,
        strokeOpacity: 0.8,
        strokeStyle: 'shortdash'
    });
    map.geoObjects.add(line);

    // Estimate distance (straight line * 1.3 for road factor)
    const R = 6371;
    const dLat = (lat2 - lat1) * Math.PI / 180;
    const dLon = (lng2 - lng1) * Math.PI / 180;
    const a = Math.sin(dLat/2) * Math.sin(dLat/2) +
        Math.cos(lat1 * Math.PI/180) * Math.cos(lat2 * Math.PI/180) *
        Math.sin(dLon/2) * Math.sin(dLon/2);
    const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1-a));
    const dist = Math.round(R * c * 1.3);
    const dur = Math.round(dist / 80 * 60); // ~80km/h avg

    routeState.ready = true;
    routeState.distance = dist * 1000;
    routeState.duration = dur * 60;
    routeState.distanceText = dist + " km";
    routeState.durationText = '';

    document.getElementById('preview-distance').innerText = routeState.distanceText;
    updateOrderButton();
    updatePriceDisplay();

    map.setBounds([[Math.min(lat1,lat2)-0.1, Math.min(lng1,lng2)-0.1], [Math.max(lat1,lat2)+0.1, Math.max(lng1,lng2)+0.1]], {
        checkZoomRange: true, zoomMargin: 60
    });
}

