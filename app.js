let globalLastRotation = null;
function calculateRotation(p1, p2) {
    if (!p1 || !p2) return globalLastRotation || 0;
    const dy = p2[0] - p1[0];
    const dx = p2[1] - p1[1];
    
    if (Math.abs(dx) < 0.000001 && Math.abs(dy) < 0.000001) {
        return globalLastRotation || 0;
    }
    
    let angle = (Math.atan2(dx, dy) * 180) / Math.PI;
    
    if (globalLastRotation !== null) {
        let diff = (angle - globalLastRotation) % 360;
        if (diff > 180) diff -= 360;
        else if (diff < -180) diff += 360;
        angle = globalLastRotation + diff;
    }
    
    globalLastRotation = angle;
    return angle;
}

