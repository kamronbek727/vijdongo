// --- Yandex Tracking Engine (Isolated Module) ---
const YandexTrackingEngine = {
    homeMap: null,
    tripMap: null,
    activeRoute: null,
    taxiMarker: null,
    interval: null,
    layoutReady: false,
    initInProgress: false,

    async ensureReady() {
        if (typeof ymaps === 'undefined') {
            console.warn("DEBUG: ymaps undefined. Waiting for API script...");
            // Wait up to 5 seconds for ymaps to appear
            for (let i = 0; i < 50; i++) {
                await new Promise(r => setTimeout(r, 100));
                if (typeof ymaps !== 'undefined') break;
            }
            if (typeof ymaps === 'undefined') {
                console.error("DEBUG: Yandex Maps API failed to load after 5s.");
                return false;
            }
        }

        if (this.initInProgress) {
            // Wait for existing init to finish
            while (this.initInProgress) {
                await new Promise(r => setTimeout(r, 100));
            }
            return true;
        }

        this.initInProgress = true;
        console.log("DEBUG: Yandex Engine initializing...");

        return new Promise((resolve) => {
            ymaps.ready(() => {
                console.log("DEBUG: ymaps.ready() fired.");
                this.registerLayouts();
                this.initInProgress = false;
                resolve(true);
            });
        });
    },

    registerLayouts() {
        if (this.layoutReady || typeof ymaps === 'undefined') return;
        
        try {
            const CarIconLayout = ymaps.templateLayoutFactory.createClass(
                '<div class="car-marker-wrapper" style="transform: rotate($[properties.iconRotate]deg); transition: transform 0.4s ease-in-out;">' +
                '<img src="rasmlar/car.png" style="width: 44px; height: 44px; filter: drop-shadow(0 4px 8px rgba(0,0,0,0.3));">' +
                '</div>'
            );
            ymaps.layout.storage.add('custom#taxiLayout', CarIconLayout);
            this.layoutReady = true;
            console.log("DEBUG: Yandex Layouts registered.");

            const img = new Image();
            img.src = "rasmlar/car.png";
        } catch (e) {
            console.error("DEBUG: Layout registration failed:", e);
        }
    },

    initHomeMap() {
        if (this.homeMap) return;
        const container = document.getElementById('home-map');
        if (!container || container.clientHeight === 0) {
            console.warn("DEBUG: home-map container not ready or hidden. Deferring init...");
            return;
        }
        console.log("DEBUG: Creating homeMap instance...");
        this.homeMap = new ymaps.Map('home-map', {
            center: [41.2995, 69.2401], zoom: 12, controls: []
        }, { 
            suppressMapOpenBlock: true, 
            yandexMapDisablePoiInteractivity: true,
            autoFitToViewport: 'always'
        });
        
        // Multiple fit attempts to force tiles
        setTimeout(() => { 
            if (this.homeMap) {
                this.homeMap.container.fitToViewport();
                this.homeMap.setZoom(this.homeMap.getZoom()); // Force redraw
            }
        }, 500);
        setTimeout(() => { if (this.homeMap) this.homeMap.container.fitToViewport(); }, 1500);
    },

    async showHomeMap() {
        await this.ensureReady();
        requestAnimationFrame(() => {
            requestAnimationFrame(() => {
                this.initHomeMap();
                if (this.homeMap) {
                    this.homeMap.container.fitToViewport();
                }
            });
        });
    },

    initTripMap() {
        if (this.tripMap) return;
        const container = document.getElementById('trip-map');
        if (!container || container.clientHeight === 0) {
            console.warn("DEBUG: trip-map container not ready or hidden. Deferring init...");
            return;
        }
        console.log("DEBUG: Creating tripMap instance...");
        this.tripMap = new ymaps.Map('trip-map', {
            center: [41.2995, 69.2401], zoom: 8, controls: []
        }, { suppressMapOpenBlock: true });
    },

    async buildHomeRoute() {
        const ready = await this.ensureReady();
        if (!ready) return;

        if (!selectedPickup.latlng || !selectedDest.latlng) {
            console.warn("DEBUG: buildHomeRoute called without pickup/dest");
            return;
        }

        // Reset route state
        routeState.ready = false;
        updateOrderButton();

        const self = this;
        const tryBuild = (attempt) => {
            self.initHomeMap();
            if (!self.homeMap) {
                if (attempt < 20) {
                    setTimeout(() => tryBuild(attempt + 1), 300);
                }
                return;
            }

            // Clear everything
            self.homeMap.geoObjects.removeAll();
            self.homeMap.container.fitToViewport();

            const lat1 = Number(selectedPickup.latlng.lat);
            const lng1 = Number(selectedPickup.latlng.lng);
            const lat2 = Number(selectedDest.latlng.lat);
            const lng2 = Number(selectedDest.latlng.lng);

            if (isNaN(lat1) || isNaN(lng1) || isNaN(lat2) || isNaN(lng2)) {
                console.error("DEBUG: Invalid coordinates", { lat1, lng1, lat2, lng2 });
                return;
            }

            console.log("DEBUG: Building route via OSRM from", [lat1, lng1], "to", [lat2, lng2]);

            // Add pickup marker (yellow)
            self.homeMap.geoObjects.add(new ymaps.Placemark([lat1, lng1],
                { hintContent: selectedPickup.address },
                { preset: 'islands#yellowCircleDotIcon', zIndex: 500 }
            ));

            // Add destination marker (black)
            self.homeMap.geoObjects.add(new ymaps.Placemark([lat2, lng2],
                { hintContent: selectedDest.address },
                { preset: 'islands#blackCircleDotIcon', zIndex: 500 }
            ));

            // Use OSRM free routing API (no API key needed)
            const osrmUrl = `https://router.project-osrm.org/route/v1/driving/${lng1},${lat1};${lng2},${lat2}?overview=full&geometries=polyline`;

            fetch(osrmUrl)
                .then(res => res.json())
                .then(data => {
                    if (data.code !== 'Ok' || !data.routes || data.routes.length === 0) {
                        console.error("DEBUG: OSRM returned no routes", data);
                        drawFallbackLine(self.homeMap, lat1, lng1, lat2, lng2);
                        return;
                    }

                    const route = data.routes[0];
                    const distanceKm = (route.distance / 1000).toFixed(0);
                    const durationMin = Math.round(route.duration / 60);
                    const hours = Math.floor(durationMin / 60);
                    const mins = durationMin % 60;

                    const distText = distanceKm + " " + t('common.km');

                    // Decode polyline geometry from OSRM
                    const routeCoords = decodeOSRMPolyline(route.geometry);

                    console.log("DEBUG: OSRM route:", distText, routeCoords.length, "points");

                    if (routeCoords.length > 0) {
                        // Draw shadow line
                        const shadowLine = new ymaps.Polyline(routeCoords, {}, {
                            strokeColor: '#00000044',
                            strokeWidth: 10,
                            strokeOpacity: 0.25,
                            zIndex: 99
                        });
                        self.homeMap.geoObjects.add(shadowLine);

                        // Draw the main black route line
                        const routeLine = new ymaps.Polyline(routeCoords, {
                            hintContent: distText
                        }, {
                            strokeColor: '#111111',
                            strokeWidth: 5,
                            strokeOpacity: 1,
                            zIndex: 100
                        });
                        self.homeMap.geoObjects.add(routeLine);
                    }

                    // Store route state
                    routeState.ready = true;
                    routeState.distance = route.distance;
                    routeState.duration = route.duration;
                    routeState.distanceText = distText;
                    routeState.durationText = '';
                    routeState.routeObject = null;

                    // Enable button
                    updateOrderButton();
                    updatePriceDisplay();

                    // Fit map to route
                    self.homeMap.container.fitToViewport();
                    const bounds = [
                        [Math.min(lat1, lat2) - 0.1, Math.min(lng1, lng2) - 0.1],
                        [Math.max(lat1, lat2) + 0.1, Math.max(lng1, lng2) + 0.1]
                    ];
                    self.homeMap.setBounds(bounds, {
                        checkZoomRange: true,
                        zoomMargin: 60
                    });
                })
                .catch(err => {
                    console.error("DEBUG: OSRM fetch error:", err);
                    drawFallbackLine(self.homeMap, lat1, lng1, lat2, lng2);
                });
        };

        requestAnimationFrame(() => {
            requestAnimationFrame(() => tryBuild(0));
        });
    },

    async startTripTracking(order) {
        const ready = await this.ensureReady();
        if (!ready) return;

        this.initTripMap();
        if (!this.tripMap) return;
        
        globalLastRotation = null;

        console.log("DEBUG: Starting trip tracking...");
        if (this.interval) clearInterval(this.interval);
        if (this._animFrame) cancelAnimationFrame(this._animFrame);
        this.tripMap.geoObjects.removeAll();
        this.tripMap.container.fitToViewport();

        const pLat = Number(order.from.lat);
        const pLng = Number(order.from.lng);
        const dLat = Number(order.to.lat);
        const dLng = Number(order.to.lng);

        const fromCoords = [pLat, pLng];
        const toCoords = [dLat, dLng];
        const driverStartCoords = [
            pLat + (Math.random() > 0.5 ? 0.005 : -0.005),
            pLng + (Math.random() > 0.5 ? 0.005 : -0.005)
        ];

        // Add pickup and destination markers
        this.tripMap.geoObjects.add(new ymaps.Placemark(fromCoords,
            { hintContent: "Olib ketish" },
            { preset: 'islands#yellowCircleDotIcon', zIndex: 200 }
        ));
        this.tripMap.geoObjects.add(new ymaps.Placemark(toCoords,
            { hintContent: "Borish manzili" },
            { preset: 'islands#blackCircleDotIcon', zIndex: 200 }
        ));

        // Fetch route from OSRM
        const osrmUrl = `https://router.project-osrm.org/route/v1/driving/${driverStartCoords[1]},${driverStartCoords[0]};${pLng},${pLat};${dLng},${dLat}?overview=full&geometries=polyline`;
        const self = this;

        fetch(osrmUrl)
            .then(res => res.json())
            .then(data => {
                if (data.code !== 'Ok' || !data.routes || data.routes.length === 0) {
                    document.getElementById('trip-status').innerText = t('trip.statusError');
                    return;
                }

                const route = data.routes[0];
                const totalDistance = route.distance; // meters
                const totalDuration = route.duration; // seconds
                const allPoints = decodeOSRMPolyline(route.geometry);

                if (allPoints.length < 2) return;

                console.log("DEBUG: Trip route:", allPoints.length, "points,",
                    (totalDistance/1000).toFixed(1), "km,",
                    Math.round(totalDuration/60), "min");

                // --- Pre-calculate cumulative distances for accurate progress ---
                const segDistances = [0]; // cumulative distance at each point
                let cumulDist = 0;
                for (let i = 1; i < allPoints.length; i++) {
                    cumulDist += haversineMeters(allPoints[i-1], allPoints[i]);
                    segDistances.push(cumulDist);
                }
                const routeTotalDist = cumulDist; // actual geometry distance

                // --- Create COMPLETED route polyline (gray, behind) ---
                const completedLine = new ymaps.Polyline([], {}, {
                    strokeColor: '#BBBBBB',
                    strokeWidth: 5,
                    strokeOpacity: 0.6,
                    zIndex: 90
                });
                self.tripMap.geoObjects.add(completedLine);

                // --- Create REMAINING route polyline (black, on top) ---
                const remainingLine = new ymaps.Polyline(allPoints, {}, {
                    strokeColor: '#111111',
                    strokeWidth: 5,
                    strokeOpacity: 1,
                    zIndex: 100
                });
                self.tripMap.geoObjects.add(remainingLine);

                // --- Create taxi marker with proper offset for accurate positioning ---
                self.taxiMarker = new ymaps.Placemark(allPoints[0], {}, {
                    iconLayout: 'custom#taxiLayout',
                    iconOffset: [-22, -22],
                    iconShape: { type: 'Circle', coordinates: [22, 22], radius: 22 },
                    iconPane: 'overlaps',
                    zIndex: 3000
                });
                self.tripMap.geoObjects.add(self.taxiMarker);

                // --- Initial map fit ---
                self.tripMap.setBounds([
                    [Math.min(pLat, dLat) - 0.02, Math.min(pLng, dLng) - 0.02],
                    [Math.max(pLat, dLat) + 0.02, Math.max(pLng, dLng) + 0.02]
                ], { checkZoomRange: true, zoomMargin: 80 });

                // --- Update initial distance ---
                updateTripInfo(totalDistance);

                // --- Animation State ---
                const SPEED_MULTIPLIER = 15; // x15 real speed for simulation
                const startTime = performance.now();
                const simDuration = (totalDuration / SPEED_MULTIPLIER) * 1000; // ms
                let lastMapPan = 0;

                // --- Smooth animation loop ---
                function animateStep(now) {
                    const elapsed = now - startTime;
                    const progress = Math.min(elapsed / simDuration, 1.0);

                    // Find the current distance traveled
                    const distTraveled = progress * routeTotalDist;

                    // Find which segment we're on via cumulative distances
                    let segIdx = 0;
                    for (let i = 1; i < segDistances.length; i++) {
                        if (segDistances[i] >= distTraveled) {
                            segIdx = i - 1;
                            break;
                        }
                        if (i === segDistances.length - 1) segIdx = i - 1;
                    }

                    // Interpolate position within the segment
                    const segStart = segDistances[segIdx];
                    const segEnd = segDistances[segIdx + 1] || segStart + 1;
                    const segProgress = Math.min((distTraveled - segStart) / (segEnd - segStart), 1);

                    const p1 = allPoints[segIdx];
                    const p2 = allPoints[segIdx + 1] || allPoints[segIdx];
                    const currentPos = [
                        p1[0] + (p2[0] - p1[0]) * segProgress,
                        p1[1] + (p2[1] - p1[1]) * segProgress
                    ];

                    // Move taxi
                    self.taxiMarker.geometry.setCoordinates(currentPos);

                    // Rotate taxi in movement direction
                    const rotation = calculateRotation(p1, p2);
                    self.taxiMarker.properties.set('iconRotate', rotation);

                    // Update polylines: completed = gray, remaining = black
                    const completedCoords = allPoints.slice(0, segIdx + 1).concat([currentPos]);
                    const remainingCoords = [currentPos].concat(allPoints.slice(segIdx + 1));

                    completedLine.geometry.setCoordinates(completedCoords);
                    remainingLine.geometry.setCoordinates(remainingCoords);

                    // Update distance display
                    const remainingFraction = 1 - progress;
                    const remainingDist = totalDistance * remainingFraction;
                    updateTripInfo(remainingDist);

                    // Gently pan map to follow taxi every 3 seconds
                    if (now - lastMapPan > 3000) {
                        lastMapPan = now;
                        self.tripMap.panTo(currentPos, { flying: false, duration: 1000 });
                    }

                    // Continue or finish
                    if (progress < 1.0) {
                        self._animFrame = requestAnimationFrame(animateStep);
                    } else {
                        // Trip complete
                        self.taxiMarker.geometry.setCoordinates(allPoints[allPoints.length - 1]);
                        completedLine.geometry.setCoordinates(allPoints);
                        remainingLine.geometry.setCoordinates([]);

                        document.getElementById('trip-status').innerText = t('trip.statusFinished');
                        document.getElementById('trip-distance').innerText = "0 " + t('common.km');

                        // Zoom to destination
                        self.tripMap.setCenter(toCoords, 15, { duration: 1000 });
                    }
                }

                // Start animation
                self._animFrame = requestAnimationFrame(animateStep);
            })
            .catch(err => {
                console.error("DEBUG: Trip OSRM error:", err);
                document.getElementById('trip-status').innerText = t('trip.statusError');
            });

        // Final fit
        setTimeout(() => { if (this.tripMap) this.tripMap.container.fitToViewport(); }, 500);
    }
};

