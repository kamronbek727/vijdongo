// --- Navigation ---
let isNavigating = false;

function navigate(screenId, animate = true) {
    // Prevent rapid double-clicks causing flicker
    if (isNavigating && animate) return;
    
    const screens = document.querySelectorAll('.screen');
    const bottomNav = document.getElementById('bottom-nav');
    const targetScreen = document.getElementById(screenId);
    
    if (!targetScreen) return;

    // Lock navigation during transition
    if (animate) {
        isNavigating = true;
        setTimeout(() => { isNavigating = false; }, 350);
    }

    // Update Bottom Nav Active State
    document.querySelectorAll('.nav-btn').forEach(btn => {
        btn.classList.remove('text-primary');
        btn.classList.add('text-textSecondary');
    });
    const activeBtn = document.getElementById(`nav-btn-${screenId}`);
    if (activeBtn) {
        activeBtn.classList.remove('text-textSecondary');
        activeBtn.classList.add('text-primary');
    }

    // Hide ALL screens except the target
    screens.forEach(screen => {
        if (screen.id === screenId) return; // skip target
        
        screen.style.pointerEvents = 'none';
        if (screen.id === currentScreen && animate) {
            // The currently visible screen: animate it out
            screen.style.transition = 'transform 0.3s ease';
            screen.style.transform = 'translateX(-100%)';
            // After animation, move it far off and hide it
            setTimeout(() => {
                if (screen.id !== currentScreen) {
                    screen.style.transition = 'none';
                    screen.style.transform = 'translateX(100%)';
                    screen.style.visibility = 'hidden';
                }
            }, 320);
        } else {
            // All other screens: instantly hide (no animation)
            screen.style.transition = 'none';
            screen.style.transform = 'translateX(100%)';
            screen.style.visibility = 'hidden';
        }
    });

    // Show target screen
    targetScreen.style.visibility = 'visible';
    targetScreen.style.pointerEvents = 'auto';
    if (animate) {
        targetScreen.style.transition = 'transform 0.3s ease';
    } else {
        targetScreen.style.transition = 'none';
    }
    targetScreen.style.transform = 'translateX(0)';
    currentScreen = screenId;

    // Bottom nav visibility
    if (['home-screen', 'safarlarim-screen', 'xabarlar-screen', 'profil-screen', 'pickup-region-screen'].includes(screenId)) {
        if (bottomNav) {
            bottomNav.style.display = 'flex';
            bottomNav.style.pointerEvents = 'auto';
        }
        // highlight home if we are in pickup/dest flow
        if (['pickup-region-screen', 'pickup-map-screen', 'dest-region-screen', 'dest-map-screen'].includes(screenId)) {
            const homeBtn = document.getElementById('nav-btn-home-screen');
            if (homeBtn) {
                homeBtn.classList.remove('text-textSecondary');
                homeBtn.classList.add('text-primary');
            }
        }
        
        // Trigger resize/fit for engine-managed maps
        setTimeout(() => {
            if (screenId === 'active-trip-screen' && YandexTrackingEngine.tripMap) {
                YandexTrackingEngine.tripMap.container.fitToViewport();
            }
        }, 350);
        
        // Refresh dynamic screens
        if (screenId === 'safarlarim-screen') renderSafarlarim();
        if (screenId === 'xabarlar-screen') renderXabarlar();
        if (screenId === 'profil-screen') renderProfil();
    } else {
        if (bottomNav) bottomNav.style.display = 'none';
        
        // Handle maps on non-nav screens
        if (['pickup-map-screen', 'dest-map-screen', 'active-trip-screen', 'taxi-screen', 'delivery-screen'].includes(screenId)) {
            setTimeout(() => {
                if (screenId === 'taxi-screen') {
                    YandexTrackingEngine.showHomeMap();
                    if (YandexTrackingEngine.homeMap) YandexTrackingEngine.homeMap.container.fitToViewport();
                    // Rebuild route if both addresses exist but route not ready
                    if (selectedPickup.latlng && selectedDest.latlng && !routeState.ready) {
                        setTimeout(() => drawHomeRoute(), 500);
                    }
                    updateOrderButton();
                    updatePriceDisplay();
                }
                if (screenId === 'delivery-screen' && delMap) {
                    delMap.container.fitToViewport();
                    updateDeliveryPriceDisplay();
                }
                if (screenId === 'pickup-map-screen' && pickupMap) {
                    pickupMap.container.fitToViewport();
                    const center = pickupMap.getCenter();
                    pickupMap.setCenter(center, pickupMap.getZoom());
                    setTimeout(() => { if (pickupMap) pickupMap.container.fitToViewport(); }, 500);
                }
                if (screenId === 'dest-map-screen' && destMap) {
                    destMap.container.fitToViewport();
                    const center = destMap.getCenter();
                    destMap.setCenter(center, destMap.getZoom());
                    setTimeout(() => { if (destMap) destMap.container.fitToViewport(); }, 500);
                }
                if (screenId === 'active-trip-screen' && tripMap) {
                    tripMap.container.fitToViewport();
                    const center = tripMap.getCenter();
                    tripMap.setCenter(center, tripMap.getZoom());
                    setTimeout(() => { if (tripMap) tripMap.container.fitToViewport(); }, 500);
                }
            }, 400);
        }
    }
}

